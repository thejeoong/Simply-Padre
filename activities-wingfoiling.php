  var bdaiAnchorLinks = $('.bdai-surf-hero a[href^="#"], .bdai-surf-story a[href^="#"], .bdai-surf-places a[href^="#"], .bdai-surf-beginners a[href^="#"], .bdai-surf-safety a[href^="#"], .bdai-surf-resources a[href^="#"], .bdai-surf-bring a[href^="#"], .bdai-surf-nearby a[href^="#"], .bdai-surf-gallery a[href^="#"], .bdai-surf-faq a[href^="#"], .bdai-surf-cta a[href^="#"]');

