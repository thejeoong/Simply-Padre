				<section class="bdai-surf-safety" id="bdai-surf-safety">
					<div class="container">
						<div class="bdai-surf-safety-heading"><span class="bdai-surf-safety-eyebrow" style="white-space:nowrap !important;width:fit-content;">Before You Enter the Water</span>

							<h2 class="bdai-surf-safety-title">Wind, Water, and Kiteboarding Safety Come First</h2>

							<p class="bdai-surf-safety-intro">Kiteboarding conditions can change quickly along the Gulf Coast. Check the current forecast, observe the actual launch area, and make a conservative decision based on your training, equipment, and ability to return safely to shore.</p>
						</div>
						<div class="bdai-surf-safety-layout">
							<div class="bdai-surf-flag-card">

								<h3>Read the Conditions Before Launch</h3>
								<div class="bdai-surf-flag-list">
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag green">Wind</span>

										<p>Confirm the direction, strength, gust range, and whether the wind is moving cleanly across the intended riding area.</p>
									</div>
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag yellow">Water</span>

										<p>Look at waves, chop, current, water depth, shore break, obstacles, and the amount of room available for a controlled launch.</p>
									</div>
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag red">Weather</span>

										<p>Delay the session when storms, lightning, rapidly changing skies, strong fronts, or other weather developments create additional risk.</p>
									</div>
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag purple">People</span>

										<p>Keep generous distance from swimmers, beach users, other riders, boats, docks, structures, and anyone who could be affected by a kite or line.</p>
									</div>
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag orange">Exit</span>

										<p>Know where you can safely land the kite and leave the water if the wind shifts, equipment fails, or conditions become uncomfortable.</p>
									</div></div><a class="bdai-surf-safety-link" href="https://www.corpuschristitx.gov/department-directory/parks-and-recreation/beaches/get-our-daily-surf-condition-flag-warning-system/" target="_blank">Check Official Beach Guidance&nbsp;<i class="bi bi-arrow-up-right" aria-hidden="true"></i></a></div>
							<div class="bdai-surf-safety-copy">
								<div class="bdai-surf-safety-point">
									<div class="bdai-surf-safety-point-icon"><i class="bi bi-wind" aria-hidden="true"></i></div>
									<div>

										<h3>Watch Wind Direction and Gusts</h3>

										<p>A wind direction that looks favorable on a forecast may behave differently at the shoreline. Gusts, lulls, shifts, and wind shadow from nearby land can affect kite control and rider stability.</p>
									</div></div>
								<div class="bdai-surf-safety-point">
									<div class="bdai-surf-safety-point-icon"><i class="bi bi-life-preserver" aria-hidden="true"></i></div>
									<div>

										<h3>Use Appropriate Safety Equipment</h3>

										<p>Use a properly fitted harness, personal flotation equipment when appropriate for your training and conditions, helmet, leash, quick-release system, and any other equipment recommended by your instructor.</p>
									</div></div>
								<div class="bdai-surf-safety-point">
									<div class="bdai-surf-safety-point-icon"><i class="bi bi-people" aria-hidden="true"></i></div>
									<div>

										<h3>Protect Space Around You</h3>

										<p>Launch and land only where there is adequate room. Keep lines, kite movement, and board travel away from swimmers, children, vehicles, buildings, rocks, poles, boats, and other water users.</p>
									</div></div>
								<div class="bdai-surf-safety-point">
									<div class="bdai-surf-safety-point-icon"><i class="bi bi-cloud-sun" aria-hidden="true"></i></div>
									<div>

										<h3>Recheck Conditions During the Session</h3>

										<p>Clouds, storms, frontal passages, tide, current, waves, and beach activity can change while you are riding. Be prepared to end the session before conditions become difficult.</p>
									</div></div></div></div></div>
				</section>
