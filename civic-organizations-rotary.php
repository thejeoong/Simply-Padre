(function($){
  var bdaiFaqCards = $('.bdai-rotary-faq-card');

  if (!bdaiFaqCards.length) {
    return;
  }

  bdaiFaqCards.each(function(bdaiIndex){
    var bdaiCard = $(this);
    var bdaiQuestion = bdaiCard.find('.bdai-rotary-faq-question').first();
    var bdaiAnswerText = bdaiCard.find('.bdai-rotary-faq-answer').first();

    if (bdaiCard.find('.bdai-rotary-faq-trigger').length || !bdaiQuestion.length || !bdaiAnswerText.length) {
      return;
    }

    var bdaiAnswerId = 'bdai-rotary-faq-answer-' + (bdaiIndex + 1);
    var bdaiTrigger = $('<button type="button"></button>');
    var bdaiIcon = $('<i aria-hidden="true"></i>');
    var bdaiIconWrap = $('<span></span>');

    bdaiTrigger.addClass('bdai-rotary-faq-trigger');
    bdaiTrigger.attr('aria-expanded', 'false');
    bdaiTrigger.attr('aria-controls', bdaiAnswerId);

    bdaiIcon.addClass('bi bi-chevron-down');
    bdaiIconWrap.addClass('bdai-rotary-faq-icon');
    bdaiIconWrap.append(bdaiIcon);

    bdaiTrigger.append(bdaiQuestion);
    bdaiTrigger.append(bdaiIconWrap);

    bdaiAnswerText.attr('id', bdaiAnswerId);
    bdaiAnswerText.prop('hidden', true);

    bdaiCard.empty();
    bdaiCard.append(bdaiTrigger);
    bdaiCard.append(bdaiAnswerText);

    bdaiTrigger.on('click', function(){
      var bdaiIsOpen = bdaiTrigger.attr('aria-expanded') === 'true';

      bdaiTrigger.attr('aria-expanded', bdaiIsOpen ? 'false' : 'true');
      bdaiCard.toggleClass('bdai-rotary-faq-open', !bdaiIsOpen);
      bdaiAnswerText.prop('hidden', bdaiIsOpen);
      bdaiIcon.toggleClass('bi-chevron-down', bdaiIsOpen);
      bdaiIcon.toggleClass('bi-chevron-up', !bdaiIsOpen);
    });
  });
})(jQuery);

