								<div class="bdai-surf-beginners-callout"><span class="bdai-surf-beginners-callout-number">01</span>
									<div><strong>Start with a friendly rally.</strong> Warm up with controlled passes and serves before keeping score. You will learn the sand, wind, court space, and communication rhythm faster without rushing into full competition.</div></div></div></div></div>
