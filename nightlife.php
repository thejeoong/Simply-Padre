<script>
(function($){
  var bdaiFaqItems = $('.bdai-nightlife-faq-item');

  if (!bdaiFaqItems.length) {
    return;
  }

  bdaiFaqItems.each(function(bdaiIndex){
    var bdaiItem = $(this);
    var bdaiQuestion = bdaiItem.find('.bdai-nightlife-faq-question-text').first();
    var bdaiAnswer = bdaiItem.find('.bdai-nightlife-faq-answer').first();

    if (bdaiItem.find('.bdai-nightlife-faq-trigger').length || !bdaiQuestion.length || !bdaiAnswer.length) {
      return;
    }

    var bdaiAnswerId = 'bdai-nightlife-answer-' + (bdaiIndex + 1);
    var bdaiTrigger = $('<button type="button"></button>');
    var bdaiChevron = $('<i aria-hidden="true"></i>');

    bdaiTrigger.addClass('bdai-nightlife-faq-trigger');
    bdaiTrigger.attr('aria-expanded', 'false');
    bdaiTrigger.attr('aria-controls', bdaiAnswerId);

    bdaiChevron.addClass('bi bi-chevron-down bdai-nightlife-faq-chevron');

    bdaiTrigger.append(bdaiQuestion);
    bdaiTrigger.append(bdaiChevron);

    bdaiAnswer.attr('id', bdaiAnswerId);
    bdaiAnswer.prop('hidden', true);

    bdaiItem.empty();
    bdaiItem.append(bdaiTrigger);
    bdaiItem.append(bdaiAnswer);

    bdaiTrigger.on('click', function(){
      var bdaiIsOpen = bdaiTrigger.attr('aria-expanded') === 'true';

      bdaiTrigger.attr('aria-expanded', bdaiIsOpen ? 'false' : 'true');
      bdaiItem.toggleClass('bdai-nightlife-faq-item-open', !bdaiIsOpen);
      bdaiAnswer.prop('hidden', bdaiIsOpen);
      bdaiChevron.toggleClass('bi-chevron-down', bdaiIsOpen);
      bdaiChevron.toggleClass('bi-chevron-up', !bdaiIsOpen);
    });
  });
})(jQuery);

