								<div class="bdai-surf-safety-point">
									<div class="bdai-surf-safety-point-icon"><i class="bi bi-wind" aria-hidden="true"></i></div>
									<div>

										<h3>Match the Wind to Your Experience</h3>

										<p>Stronger wind can increase speed, sail pressure, and the difficulty of returning to shore. New riders should learn in conditions that leave room for controlled practice and recovery.</p>
									</div></div>
								<div class="bdai-surf-safety-point">
									<div class="bdai-surf-safety-point-icon"><i class="bi bi-life-preserver" aria-hidden="true"></i></div>
									<div>

										<h3>Use Appropriate Safety Equipment</h3>

										<p>Wear a properly fitted personal flotation device where appropriate, use equipment in good condition, and make sure your board, rig, and connections are suitable for the session.</p>
									</div></div>
								<div class="bdai-surf-safety-point">
									<div class="bdai-surf-safety-point-icon"><i class="bi bi-water" aria-hidden="true"></i></div>
									<div>

										<h3>Respect Currents and Shallow Water</h3>

										<p>Lagoon and bay water may be shallow, but shallow areas can include seagrass beds, mud flats, changing depth, and limited room to maneuver. Navigate carefully and avoid damaging the bottom.</p>
									</div></div>
								<div class="bdai-surf-safety-point">
									<div class="bdai-surf-safety-point-icon"><i class="bi bi-cloud-sun" aria-hidden="true"></i></div>
									<div>

										<h3>Recheck the Weather</h3>

										<p>Conditions can shift during the day. Keep checking the sky, wind, water, and nearby activity, and return to shore early if the session stops feeling controlled.</p>
									</div></div></div></div></div>
