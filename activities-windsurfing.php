							<h2 class="bdai-surf-safety-title">Read the Conditions Before You Rig</h2>

							<p class="bdai-surf-safety-intro">Windsurfing conditions around North Padre Island and Corpus Christi can change with wind direction, wind strength, tide, current, waves, weather, and water traffic. Use current information and local guidance before choosing where and when to go.</p>
						</div>
						<div class="bdai-surf-safety-layout">
							<div class="bdai-surf-flag-card">

								<h3>Understand the Day Before You Launch</h3>
								<div class="bdai-surf-flag-list">
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag green">Wind</span>

										<p>Look at the current wind direction and strength, then consider whether the breeze is steady enough and appropriate for your experience.</p>
									</div>
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag yellow">Water</span>

										<p>Check whether the water is shallow, choppy, wavy, or affected by current. A protected lagoon and an exposed Gulf beach can feel very different.</p>
									</div>
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag red">Weather</span>

										<p>Watch for storms, lightning, rapidly changing skies, poor visibility, or other conditions that make remaining on the water unsafe.</p>
									</div>
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag purple">Traffic</span>

										<p>Give boats, swimmers, paddlers, anglers, and other windsurfers space. Choose a launch and sailing area that allows you to maintain control.</p>
									</div>
									<div class="bdai-surf-flag-item"><span class="bdai-surf-flag orange">Ability</span>

										<p>Stay within your ability to launch, sail upwind, recover your equipment, and return to shore if the wind or water changes.</p>
									</div></div><a class="bdai-surf-safety-link" href="https://www.nps.gov/pais/planyourvisit/boating.htm" target="_blank">Read Official Park Guidance&nbsp;<i class="bi bi-arrow-up-right" aria-hidden="true"></i></a></div>
