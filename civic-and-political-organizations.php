<script>
(function () {
    var civicImageSelector = '.bdai-civic-page .cloned-table td img, .bdai-civic-page > table:last-of-type td img';

    function getFrameHeight() {
        if (window.innerWidth <= 600) {
            return 180;
        }
        if (window.innerWidth <= 1000) {
            return 200;
        }
        return 220;
    }

    function clearImageFrameClasses(imageWrapper) {
        imageWrapper.classList.remove('bdai-image-frame-wide');
        imageWrapper.classList.remove('bdai-image-frame-tall');
        imageWrapper.classList.remove('bdai-image-frame-balanced');
    }

    function classifyImageFrame(imageElement, imageWrapper) {
        var imageWidth = imageElement.naturalWidth;
        var imageHeight = imageElement.naturalHeight;
        var frameWidth = imageWrapper.clientWidth;
        var frameHeight = imageWrapper.clientHeight;
        var imageRatio;
        var frameRatio;

        if (!imageWidth || !imageHeight || !frameWidth || !frameHeight) {
            return;
        }

        imageRatio = imageWidth / imageHeight;
        frameRatio = frameWidth / frameHeight;
        clearImageFrameClasses(imageWrapper);

        imageElement.style.width = '';
        imageElement.style.height = '';
        imageElement.style.maxWidth = '100%';
        imageElement.style.maxHeight = '100%';
        imageElement.style.objectFit = 'contain';

        if (imageRatio > frameRatio * 1.05) {
            imageWrapper.classList.add('bdai-image-frame-wide');
            imageElement.style.width = '100%';
            imageElement.style.height = 'auto';
            imageElement.style.maxWidth = '100%';
            imageElement.style.maxHeight = '100%';
        } else if (imageRatio < frameRatio / 1.05) {
            imageWrapper.classList.add('bdai-image-frame-tall');
            imageElement.style.width = 'auto';
            imageElement.style.height = '100%';
            imageElement.style.maxWidth = '100%';
            imageElement.style.maxHeight = '100%';
        } else {
            imageWrapper.classList.add('bdai-image-frame-balanced');
            imageElement.style.width = '100%';
            imageElement.style.height = 'auto';
            imageElement.style.maxWidth = '100%';
            imageElement.style.maxHeight = '100%';
        }
    }

    function addBlurredBackground(imageElement) {
        var imageWrapper = imageElement.parentElement;
        var imageSource;
        var blurredBackground;
        var frameHeight;

        if (!imageWrapper) {
            return;
        }

        frameHeight = getFrameHeight();
        imageWrapper.style.position = 'relative';
        imageWrapper.style.display = 'flex';
        imageWrapper.style.alignItems = 'center';
        imageWrapper.style.justifyContent = 'center';
        imageWrapper.style.width = '100%';
        imageWrapper.style.height = frameHeight + 'px';
        imageWrapper.style.minHeight = frameHeight + 'px';
        imageWrapper.style.margin = '0 0 16px 0';
        imageWrapper.style.padding = '0';
        imageWrapper.style.boxSizing = 'border-box';
        imageWrapper.style.overflow = 'hidden';
        imageWrapper.style.backgroundColor = 'rgb(214,234,246)';

        imageElement.style.position = 'relative';
        imageElement.style.zIndex = '1';
        imageElement.style.display = 'block';
        imageElement.style.maxWidth = '100%';
        imageElement.style.maxHeight = '100%';
        imageElement.style.margin = '0 auto';
        imageElement.style.padding = '0';
        imageElement.style.objectFit = 'contain';
        imageElement.style.objectPosition = 'center center';
        imageElement.style.border = '0';
        imageElement.style.borderRadius = '4px';

        blurredBackground = imageWrapper.querySelector('.bdai-img-blur-bg');
        if (!blurredBackground) {
            blurredBackground = document.createElement('div');
            blurredBackground.className = 'bdai-img-blur-bg';
            blurredBackground.setAttribute('aria-hidden', 'true');
            imageWrapper.insertBefore(blurredBackground, imageElement);
        }

        imageSource = imageElement.currentSrc || imageElement.src;
        if (imageSource) {
            blurredBackground.style.position = 'absolute';
            blurredBackground.style.top = '-12px';
            blurredBackground.style.right = '-12px';
            blurredBackground.style.bottom = '-12px';
            blurredBackground.style.left = '-12px';
            blurredBackground.style.zIndex = '0';
            blurredBackground.style.pointerEvents = 'none';
            blurredBackground.style.backgroundImage = 'url(' + imageSource + ')';
            blurredBackground.style.backgroundPosition = 'center center';
            blurredBackground.style.backgroundSize = 'cover';
            blurredBackground.style.backgroundRepeat = 'no-repeat';
            blurredBackground.style.filter = 'blur(16px)';
            blurredBackground.style.transform = 'scale(1.15)';
        }

        classifyImageFrame(imageElement, imageWrapper);
    }

    function updateImageFrames() {
        var imageElements = document.querySelectorAll(civicImageSelector);
        var imageIndex;

        for (imageIndex = 0; imageIndex < imageElements.length; imageIndex++) {
            addBlurredBackground(imageElements[imageIndex]);
        }
    }

    function initializeCivicImages() {
        var imageElements = document.querySelectorAll(civicImageSelector);
        var imageIndex;

        for (imageIndex = 0; imageIndex < imageElements.length; imageIndex++) {
            if (imageElements[imageIndex].complete && imageElements[imageIndex].naturalWidth > 0) {
                addBlurredBackground(imageElements[imageIndex]);
            } else {
                imageElements[imageIndex].addEventListener('load', function () {
                    addBlurredBackground(this);
                });
            }
        }

        updateImageFrames();
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initializeCivicImages);
    } else {
        initializeCivicImages();
    }

    window.addEventListener('resize', updateImageFrames);
})();
</script>