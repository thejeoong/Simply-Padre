<script>
(function($){
  var bdaiFaqCards = $('.bdai-porta-faq-card');

  if (!bdaiFaqCards.length) {
    return;
  }

  bdaiFaqCards.each(function(bdaiIndex){
    var bdaiCard = $(this);
    var bdaiQuestion = bdaiCard.find('.bdai-porta-faq-question').first();
    var bdaiAnswerText = bdaiCard.find('.bdai-porta-faq-answer').first();

    if (bdaiCard.find('.bdai-porta-faq-trigger').length || !bdaiQuestion.length || !bdaiAnswerText.length) {
      return;
    }

    var bdaiAnswerId = 'bdai-porta-faq-answer-' + (bdaiIndex + 1);
    var bdaiTrigger = $('<button type="button"></button>');
    var bdaiIcon = $('<i aria-hidden="true"></i>');
    var bdaiIconWrap = $('<span></span>');

    bdaiTrigger.addClass('bdai-porta-faq-trigger');
    bdaiTrigger.attr('aria-expanded', 'false');
    bdaiTrigger.attr('aria-controls', bdaiAnswerId);

    bdaiIcon.addClass('bi bi-chevron-down');
    bdaiIconWrap.addClass('bdai-porta-faq-icon');
    bdaiIconWrap.append(bdaiIcon);

    bdaiTrigger.append(bdaiQuestion);
    bdaiTrigger.append(bdaiIconWrap);

    bdaiAnswerText.attr('id', bdaiAnswerId);
    bdaiAnswerText.prop('hidden', true);

    bdaiCard.empty();
    bdaiCard.append(bdaiTrigger);
    bdaiCard.append(bdaiAnswerText);

    bdaiTrigger.on('click', function(){
      var bdaiIsOpen = bdaiTrigger.attr('aria-expanded') === 'true';

      bdaiTrigger.attr('aria-expanded', bdaiIsOpen ? 'false' : 'true');
      bdaiCard.toggleClass('bdai-faq-open', !bdaiIsOpen);
      bdaiAnswerText.prop('hidden', bdaiIsOpen);
    });
  });
})(jQuery);
</script>

<script>
(function(){
  var bdaiReveals = function(){
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches || !window.IntersectionObserver) {
      return;
    }
    var items = document.querySelectorAll('.bdai-reveal');
    if (!items.length) {
      return;
    }
    for (var i = 0; i < items.length; i++) {
      items[i].classList.add('bdai-hidden');
    }
    var obs = new IntersectionObserver(function(entries, observer){
      for (var j = 0; j < entries.length; j++){
        if (entries[j].isIntersecting){
          entries[j].target.classList.remove('bdai-hidden');
          observer.unobserve(entries[j].target);
        }
      }
    }, { threshold:0.1, rootMargin:'0px' });
    for (var k = 0; k < items.length; k++) {
      obs.observe(items[k]);
    }
  };
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', bdaiReveals);
  } else {
    bdaiReveals();
  }
})();
</script>